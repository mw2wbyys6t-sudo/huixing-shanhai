def main():
    dump = json.loads(Path(__file__).with_name("table_v5_dump.json").read_text(encoding="utf-8"))
    spots_path = BASE_DIR / "data" / "scenic_spots.json"
    fe_path = BASE_DIR / "frontend" / "lib" / "scenic_data.json"

    spots = json.loads(spots_path.read_text(encoding="utf-8"))
    fe = json.loads(fe_path.read_text(encoding="utf-8"))
    fe_by_id = {s["id"]: s for s in fe}

    table_by_id = {s.get("景区ID"): s for s in dump}
    enriched = 0
    added = 0

    # 1) 既有 318 个国内景区：补 43 字段中的新维度
    for s in spots:
        row = table_by_id.get(s["id"])
        if not row:
            continue
        for col, field in FIELD_MAP.items():
            val = clean(row.get(col))
            if val:
                s[field] = val
        enriched += 1
        f = fe_by_id.get(s["id"])
        if f:
            for col, field in FIELD_MAP.items():
                val = clean(row.get(col))
                if val:
                    f[field] = val

    # 2) 22 个新景区建卡
    existing_ids = {s["id"] for s in spots}
    for tid, meta in NEW_SPOTS.items():
        if tid in existing_ids:
            continue
        row = table_by_id.get(tid, {})
        spot = {
            "id": tid,
            "name": row.get("景区名称", tid),
            "province": row.get("省级行政区", ""),
            "city": row.get("城市/地区", ""),
            "type": row.get("景区类型", "名胜").split("/")[-1],
            "level": meta["level"],
            "rating": 4.4,
            "review_count": "2.1w",
            "description": meta["desc"],
            "images": [],
            "latitude": meta["lat"],
            "longitude": meta["lng"],
            "best_season": row.get("最佳季节") or "全年",
            "tags": ["名胜"],
            "ticket": meta["ticket"],
            "transport": meta["transport"],
            "avoid": {"avoid_index": 2.2, "avoid_tags": ["提前规划", "关注天气"],
                      "best_time": row.get("最佳季节") or "全年",
                      "tips": "热门时段建议提前预约，错峰出行体验更佳。"},
        }
        # 表格里其余维度字段
        for col, field in FIELD_MAP.items():
            val = clean(row.get(col))
            if val:
                spot[field] = val
        spots.append(spot)
        fe.append(json.loads(json.dumps(spot)))
        added += 1

    spots_path.write_text(json.dumps(spots, ensure_ascii=False, indent=2), encoding="utf-8")
    fe_path.write_text(json.dumps(fe, ensure_ascii=False, indent=2), encoding="utf-8")

    print(f"既有景区字段补全: {enriched} | 新增景区: {added}")
    print(f"总景区数: {len(spots)}（国内 {sum(1 for s in spots if s['id'].startswith('CN-'))} + 国际 {sum(1 for s in spots if s['id'].startswith('GL-'))}）")
    print(f"新增维度字段: {len(FIELD_MAP)} 个")


if __name__ == "__main__":
    main()
