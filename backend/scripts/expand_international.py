def curl(url: str, head: bool = False, timeout: int = 20) -> tuple[int, bytes]:
    """直连失败自动走代理的 curl 封装，返回 (HTTP状态码, 响应体)"""
    for use_proxy in (False, True):
        cmd = ["curl", "-s", "--max-time", str(timeout), "-o", "-", "-w", "\n%{http_code}",
               "-A", "Mozilla/5.0 (Windows NT 10.0; Win64; x64) huixing-crawler/1.0"]
        if use_proxy:
            cmd += ["-x", PROXY]
        if head:
            cmd += ["-I", "-L"]
        else:
            cmd += ["-L"]
        cmd.append(url)
        try:
            raw = subprocess.check_output(cmd, timeout=timeout + 10)
            body, _, code = raw.rpartition(b"\n")
            try:
                return int(code.strip()), body
            except ValueError:
                continue
        except (subprocess.SubprocessError, OSError):
            continue
    return 0, b""


def commons_image(query: str) -> str | None:
    """Commons API 检索真实文件名，返回可访问的 Special:FilePath URL"""
    api = ("https://commons.wikimedia.org/w/api.php?action=query&list=search"
           f"&srsearch={quote(query)}&srnamespace=6&srlimit=6&format=json")
    code, body = curl(api)
    if code != 200:
        return None
    try:
        hits = json.loads(body)["query"]["search"]
    except (json.JSONDecodeError, KeyError):
        return None
    for hit in hits:
        title = hit.get("title", "")  # "File:xxx.jpg"
        if not title.lower().split(".")[-1] in ("jpg", "jpeg", "png"):
            continue
        url = f"https://commons.wikimedia.org/wiki/Special:FilePath/{quote(title[5:])}?width=800"
        vcode, _ = curl(url, head=True, timeout=25)
        if vcode == 200:
            return url
        time.sleep(0.3)
    return None


