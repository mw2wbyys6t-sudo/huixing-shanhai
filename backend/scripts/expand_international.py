def main():
    spots_path = BASE_DIR / "data" / "scenic_spots.json"
    fe_path = BASE_DIR / "frontend" / "lib" / "scenic_data.json"

    spots = json.loads(spots_path.read_text(encoding="utf-8"))
    fe = json.loads(fe_path.read_text(encoding="utf-8"))
    existing_ids = {s["id"] for s in spots}

    added = []
    for item in NEW_SPOTS:
        if item["id"] in existing_ids:
            continue
        img = commons_image(item["img"])
        if not img:
            print(f"[WARN] {item['id']} {item['name']}: 未找到可访问的 Commons 图片，占位空图")
        spot = {
            "id": item["id"],
            "name": item["name"],
            "province": item["province"],
            "city": item["city"],
            "type": item["type"],
            "level": item["level"],
            "rating": item["rating"],
            "review_count": item["review_count"],
            "description": item["desc"],
            "images": [img] if img else [],
            "latitude": item["lat"],
            "longitude": item["lng"],
            "best_season": item["best_season"],
            "tags": item["tags"],
            "avoid": {
                "avoid_index": item["avoid"]["idx"],
                "avoid_tags": item["avoid"]["tags"],
                "best_time": item["avoid"]["best"],
                "tips": item["avoid"]["tips"],
            },
        }
        spots.append(spot)
        fe.append(json.loads(json.dumps(spot)))
        added.append(f"{item['id']} {item['name']}{' ✓图' if img else ' ✗无图'}")
        time.sleep(0.4)

    spots_path.write_text(json.dumps(spots, ensure_ascii=False, indent=2), encoding="utf-8")
    fe_path.write_text(json.dumps(fe, ensure_ascii=False, indent=2), encoding="utf-8")

    print(f"新增 {len(added)} 个景区，总计 {len(spots)} 个")
    for line in added:
        print(" -", line)


if __name__ == "__main__":
    main()
